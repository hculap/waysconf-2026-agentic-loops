/**
 * Every registry below holds references to nodes, styles and variables in the
 * document. A second build removes all of them, so carrying the old references
 * into it would bind fills to variables that no longer exist. Clear first.
 */
function resetState() {
  V = {};
  RGB = {};
  STYLES = {};
  SPEC = {};
  COMP = {};
  PROPS = {};
  LAYERS = {};
  PAGES = {};
  COLLECTIONS = {};
  WARNINGS = [];
  STEP = 0;
}

async function build(replace) {
  var started = Date.now();
  resetState();

  if (!D) {
    figma.notify('data.generated.js was not built. Run: node scripts/build-figma-plugin.mjs');
    send('done', { ok: false, message: 'No data. Run node scripts/build-figma-plugin.mjs and re-import the plugin.' });
    return;
  }

  if (looksBuilt()) {
    if (!replace) {
      send('needs-replace', null);
      figma.notify('This file already has a TURBINE build. Tick "Replace" to rebuild it.');
      return;
    }
    await clearPrevious();
  }

  await loadFonts();
  await breathe();

  await buildPages();
  await setCurrentPage(PAGES['Design system']);
  await buildVariables();
  await breathe();
  await buildTextStyles();
  await breathe();

  var ds = PAGES['Design system'];
  await buildButton(ds);
  await buildInput(ds);
  await buildNav(ds);
  await buildTabBar(ds);
  await buildArtistCard(ds);
  await buildTicketCard(ds);
  await buildTimetableRow(ds);
  await buildFaqRow(ds);
  await buildTicker(ds);
  await buildFooter(ds);
  await buildSkipLink(ds);
  await breathe();

  step('Laying out the Design system page');
  await buildDesignSystemPage();
  await breathe();

  var i;
  for (i = 0; i < D.breakpoints.length; i = i + 1) {
    await buildViewport(D.breakpoints[i]);
    await breathe();
  }

  await buildCoverPage();
  await buildExportsPage();
  await setCurrentPage(PAGES['Desktop 1440']);

  step('Finished');
  var seconds = Math.round((Date.now() - started) / 1000);
  var summary =
    'TURBINE built: ' +
    D.tokens.color.length +
    ' colour variables, ' +
    D.textStyles.length +
    ' text styles, ' +
    Object.keys(COMP).length +
    ' components, 3 breakpoints, ' +
    D.exports.rows.length +
    ' export targets — ' +
    seconds +
    's';
  send('done', { ok: true, message: summary, warnings: WARNINGS.length, seconds: seconds });
  figma.notify(summary + (WARNINGS.length ? ' · ' + WARNINGS.length + ' warnings in the log' : ''), {
    timeout: 8000
  });
}

