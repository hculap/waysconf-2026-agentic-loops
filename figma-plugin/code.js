/**
 * FIGMA-SPEC §8.3: PNG, 1x, sRGB, contents-only off.
 *
 * The suffix carries the breakpoint. Figma takes the base filename from the layer
 * name, and the same ten section frames appear in all three viewport frames, so
 * without a suffix an export of all thirty produces section-hero.png three times.
 * §8.3's "suffix: none" rules out the @2x-style scale suffixes Figma adds at other
 * scales; it is not a reason to lose the one piece of the filename §8.2 requires.
 */
function setExport(node, suffix) {
  var withProfile = [
    {
      format: 'PNG',
      constraint: { type: 'SCALE', value: 1 },
      contentsOnly: false,
      suffix: suffix,
      colorProfile: 'SRGB'
    }
  ];
  try {
    node.exportSettings = withProfile;
    return;
  } catch (error) {
    /* colorProfile arrived later than the rest of ExportSettingsImage. */
  }
  try {
    node.exportSettings = [
      { format: 'PNG', constraint: { type: 'SCALE', value: 1 }, contentsOnly: false, suffix: suffix }
    ];
  } catch (second) {
    warn('Could not set export settings on ' + node.name);
  }
}

async function buildViewport(bp) {
  step('Composing ' + bp.frame);
  var page = PAGES[bp.page];
  var root = frame(bp.frame, { dir: 'VERTICAL', gap: 0, fill: 'color/bg/base' });
  page.appendChild(root);
  root.x = 0;
  root.y = 0;
  fixWidth(root, bp.width);
  setSizing(root, 'v', 'HUG');

  /* Setting the mode is what makes the type and gutters resize. Nothing is retyped. */
  var responsive = COLLECTIONS['TURBINE / Responsive'];
  if (responsive) {
    var modeId = null;
    var m;
    for (m = 0; m < responsive.modes.length; m = m + 1) {
      if (responsive.modes[m].name === bp.mode) modeId = responsive.modes[m].modeId;
    }
    if (modeId) {
      try {
        root.setExplicitVariableModeForCollection(responsive, modeId);
      } catch (error) {
        try {
          root.setExplicitVariableModeForCollection(responsive.id, modeId);
        } catch (second) {
          warn('Could not set the ' + bp.mode + ' mode on ' + bp.frame);
        }
      }
    }
  }

  root.layoutGrids = [
    {
      pattern: 'COLUMNS',
      alignment: 'STRETCH',
      count: bp.gridColumns,
      gutterSize: bp.gridGutter,
      offset: Math.round((bp.width - bp.container) / 2),
      visible: false,
      color: { r: 1, g: 0, b: 0, a: 0.1 }
    }
  ];

  var i;
  for (i = 0; i < SECTION_BUILDERS.length; i = i + 1) {
    var section = await SECTION_BUILDERS[i].build(bp);
    append(root, section, 'FILL');
    setExport(section, '-' + bp.width);
    await breathe();
  }

  setExport(root, '-' + bp.width);
  try {
    root.devStatus = { type: 'READY_FOR_DEV' };
  } catch (error) {
    /* devStatus needs a Dev-Mode-capable plan. The rest of the file is unaffected. */
  }

  /* The five interactive areas CANON §9 makes non-negotiable demands about. */
  var annotations = D.annotations;
  var a;
  for (a = 0; a < annotations.length; a = a + 1) {
    var target = find(root, annotations[a].target);
    if (target) annotate(target, annotations[a].text);
  }
  return root;
}

