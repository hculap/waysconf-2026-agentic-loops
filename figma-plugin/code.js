async function setCurrentPage(page) {
  if (typeof figma.setCurrentPageAsync === 'function') {
    try {
      await figma.setCurrentPageAsync(page);
      return;
    } catch (error) {
      /* Fall through. */
    }
  }
  try {
    figma.currentPage = page;
  } catch (error) {
    /* Building continues on whichever page is open. */
  }
}

async function buildPages() {
  step('Creating six pages');
  if (typeof figma.loadAllPagesAsync === 'function') {
    try {
      await figma.loadAllPagesAsync();
    } catch (error) {
      /* Only needed under dynamic-page document access. */
    }
  }
  var names = D.pages;
  var i;
  var first = figma.currentPage;
  first.name = names[0];
  PAGES[names[0]] = first;
  for (i = 1; i < names.length; i = i + 1) {
    var page = figma.createPage();
    page.name = names[i];
    figma.root.appendChild(page);
    PAGES[names[i]] = page;
  }
  log('Pages: ' + names.join(', '));
}

