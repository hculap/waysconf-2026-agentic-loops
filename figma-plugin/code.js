function weightVariableName(weight) {
  var weights = D.tokens.type.weight;
  var i;
  for (i = 0; i < weights.length; i = i + 1) {
    if (weights[i].value === weight) return weights[i].name;
  }
  return null;
}

function bindStyleField(style, field, varName) {
  var variable = varName ? V[varName] : null;
  if (!variable) return;
  try {
    style.setBoundVariable(field, variable);
  } catch (error) {
    /* Binding family or weight fails when the resolved face is not installed.
       The literal value is already set, so the style still renders correctly. */
  }
}

async function buildTextStyles() {
  step('Creating the seventeen text styles');
  var specs = D.textStyles;
  var i;
  for (i = 0; i < specs.length; i = i + 1) {
    var spec = specs[i];
    SPEC[spec.name] = spec;

    var style = figma.createTextStyle();
    style.name = spec.name;
    style.fontName = fontFor(spec.figmaFamily, spec.weight);
    style.fontSize = spec.px;

    var percent = spec.leadingPercent;
    if (percent === undefined) {
      var leading = D.tokens.type.leading;
      var k;
      for (k = 0; k < leading.length; k = k + 1) {
        if (leading[k].name === spec.leading) percent = leading[k].percent;
      }
    }
    style.lineHeight = { unit: 'PERCENT', value: percent };

    var trackingPercent = 0;
    var tracking = D.tokens.type.tracking;
    var t;
    for (t = 0; t < tracking.length; t = t + 1) {
      if (tracking[t].name === spec.tracking) trackingPercent = tracking[t].percent;
    }
    style.letterSpacing = { unit: 'PERCENT', value: trackingPercent };
    style.textCase = spec.textCase;
    style.description = spec.usedBy;

    bindStyleField(style, 'fontFamily', 'font/' + spec.family);
    bindStyleField(style, 'fontWeight', weightVariableName(spec.weight));
    bindStyleField(style, 'fontSize', spec.size);
    bindStyleField(style, 'letterSpacing', spec.tracking);
    if (spec.leadingPercent === undefined) bindStyleField(style, 'lineHeight', spec.leading);

    STYLES[spec.name] = style;
  }
  log(specs.length + ' text styles, each bound to its variables');
}

