function byName(name) {
  return function (node) {
    return node.name === name;
  };
}

function find(root, name) {
  if (!root || typeof root.findOne !== 'function') return null;
  return root.findOne(byName(name));
}

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

/** A solid paint bound to a colour variable, with the literal as a visible fallback. */
function solid(varName, opacity) {
  var rgb = RGB[varName] || { r: 1, g: 0, b: 1 };
  var paint = {
    type: 'SOLID',
    color: { r: rgb.r, g: rgb.g, b: rgb.b },
    opacity: opacity === undefined ? 1 : opacity
  };
  var variable = V[varName];
  if (variable) {
    try {
      return figma.variables.setBoundVariableForPaint(paint, 'color', variable);
    } catch (error) {
      warn('Could not bind a fill to ' + varName + ': ' + error.message);
    }
  }
  return paint;
}

function setFill(node, varName, opacity) {
  node.fills = [solid(varName, opacity)];
}

function setStroke(node, varName, weight, align) {
  node.strokes = [solid(varName)];
  node.strokeWeight = weight === undefined ? 1 : weight;
  node.strokeAlign = align || 'INSIDE';
}

/** Individual border sides, which is how every hairline in the spec is described. */
function setBorder(node, varName, sides) {
  node.strokes = [solid(varName)];
  node.strokeAlign = 'INSIDE';
  node.strokeTopWeight = sides.top || 0;
  node.strokeRightWeight = sides.right || 0;
  node.strokeBottomWeight = sides.bottom || 0;
  node.strokeLeftWeight = sides.left || 0;
}

/** Bind a numeric field to a FLOAT variable. Silent when the field is not bindable. */
function bindNum(node, field, varName) {
  var variable = V[varName];
  if (!variable) return;
  try {
    node.setBoundVariable(field, variable);
  } catch (error) {
    try {
      node.setBoundVariable(field, variable.id);
    } catch (second) {
      /* Not every field is bindable in every host version. The literal stands. */
    }
  }
}

function setPadding(node, pad) {
  if (pad === undefined || pad === null) return;
  if (typeof pad === 'number') {
    node.paddingTop = pad;
    node.paddingRight = pad;
    node.paddingBottom = pad;
    node.paddingLeft = pad;
    return;
  }
  var x = pad.x === undefined ? 0 : pad.x;
  var y = pad.y === undefined ? 0 : pad.y;
  node.paddingTop = pad.top === undefined ? y : pad.top;
  node.paddingRight = pad.right === undefined ? x : pad.right;
  node.paddingBottom = pad.bottom === undefined ? y : pad.bottom;
  node.paddingLeft = pad.left === undefined ? x : pad.left;
}

function applyLayout(node, options) {
  var o = options || {};
  node.layoutMode = o.dir || 'VERTICAL';
  node.primaryAxisSizingMode = 'AUTO';
  node.counterAxisSizingMode = 'AUTO';
  node.itemSpacing = o.gap || 0;
  node.primaryAxisAlignItems = o.justify || 'MIN';
  node.counterAxisAlignItems = o.align || 'MIN';
  node.clipsContent = o.clip === true;
  setPadding(node, o.pad);
  if (o.wrap) {
    node.layoutWrap = 'WRAP';
    node.counterAxisSpacing = o.rowGap === undefined ? node.itemSpacing : o.rowGap;
  }
  if (o.radius !== undefined) node.cornerRadius = o.radius;
  if (o.fill) setFill(node, o.fill);
  else node.fills = [];
  return node;
}

function frame(name, options) {
  var f = figma.createFrame();
  f.name = name;
  return applyLayout(f, options);
}

function componentFrame(name, options) {
  var c = figma.createComponent();
  c.name = name;
  return applyLayout(c, options);
}

function setSizing(node, axis, mode) {
  try {
    if (axis === 'h') node.layoutSizingHorizontal = mode;
    else node.layoutSizingVertical = mode;
  } catch (error) {
    /* FILL needs an auto-layout parent; HUG needs an auto-layout node. */
  }
}

/** Append, then size. Sizing a node that is not yet in an auto-layout parent throws. */
function append(parent, child, h, v) {
  parent.appendChild(child);
  if (h) setSizing(child, 'h', h);
  if (v) setSizing(child, 'v', v);
  return child;
}

/**
 * Pin one axis of an auto-layout node.
 *
 * Order matters and the obvious order is wrong: resizing a frame that is still set
 * to hug does nothing, because it hugs straight back to its contents. The axis has
 * to become FIXED first. Which sizing mode that is depends on the layout direction —
 * width is the primary axis of a horizontal frame and the counter axis of a vertical
 * one — so both are handled rather than assumed.
 */
function pinAxis(node, axis) {
  try {
    if (node.layoutMode === 'HORIZONTAL') {
      if (axis === 'h') node.primaryAxisSizingMode = 'FIXED';
      else node.counterAxisSizingMode = 'FIXED';
    } else if (node.layoutMode === 'VERTICAL') {
      if (axis === 'h') node.counterAxisSizingMode = 'FIXED';
      else node.primaryAxisSizingMode = 'FIXED';
    }
  } catch (error) {
    /* Not an auto-layout node; resize alone is enough. */
  }
  setSizing(node, axis, 'FIXED');
}

function fixWidth(node, width) {
  pinAxis(node, 'h');
  try {
    node.resize(width, Math.max(node.height, 1));
  } catch (error) {
    warn('Could not resize ' + node.name + ' to ' + width);
  }
}

function fixHeight(node, height) {
  pinAxis(node, 'v');
  try {
    node.resize(Math.max(node.width, 1), height);
  } catch (error) {
    warn('Could not set the height of ' + node.name);
  }
}

function fixSize(node, width, height) {
  pinAxis(node, 'h');
  pinAxis(node, 'v');
  try {
    node.resize(width, height);
  } catch (error) {
    warn('Could not resize ' + node.name);
  }
}

function setMaxWidth(node, value) {
  try {
    node.maxWidth = value;
  } catch (error) {
    /* maxWidth arrived with auto-layout v4. Older hosts keep the fixed width. */
  }
}

function setMinHeight(node, value) {
  try {
    node.minHeight = value;
  } catch (error) {
    /* As above. */
  }
}

/** Lift a child out of the flow so it can sit over its parent, as a scrim or ring does. */
function absolute(node, constraints) {
  try {
    node.layoutPositioning = 'ABSOLUTE';
  } catch (error) {
    return node;
  }
  if (constraints) {
    try {
      node.constraints = constraints;
    } catch (error) {
      /* Ignore: the node still sits where it was put. */
    }
  }
  return node;
}

function annotate(node, label) {
  try {
    node.annotations = [{ label: label }];
  } catch (error) {
    /* Annotations need a Dev-Mode-capable file. Keep the note reachable anyway. */
  }
  try {
    node.setPluginData('note', label);
  } catch (error) {
    /* Nothing further to do. */
  }
}

/* ==========================================================================
   3. Fonts
   --------------------------------------------------------------------------
   Nothing in this plugin may create a text node before this has finished.
   ========================================================================== */

function fontKey(family, weight) {
  return family + '|' + weight;
}

function fontFor(family, weight) {
  return FONTS[fontKey(family, weight)] || { family: 'Inter', style: 'Regular' };
}

var FALLBACK_STYLE = { 400: 'Regular', 500: 'Medium', 600: 'Semi Bold', 700: 'Bold' };

async function loadFonts() {
  step('Loading fonts');
  var wanted = D.tokens.fonts;
  var i;
  var j;

  /* Inter Regular is the default face of every new text node, so it is loaded
     first and unconditionally: without it figma.createText itself fails. */
  await figma.loadFontAsync({ family: 'Inter', style: 'Regular' });
  FONTS[fontKey('Inter', 400)] = { family: 'Inter', style: 'Regular' };

  for (i = 0; i < wanted.length; i = i + 1) {
    var want = wanted[i];
    var loaded = null;
    for (j = 0; j < want.candidates.length && !loaded; j = j + 1) {
      var candidate = { family: want.family, style: want.candidates[j] };
      try {
        await figma.loadFontAsync(candidate);
        loaded = candidate;
      } catch (error) {
        /* Try the next spelling of the weight. */
      }
    }
    if (!loaded) {
      var substitute = { family: 'Inter', style: FALLBACK_STYLE[want.weight] || 'Regular' };
      try {
        await figma.loadFontAsync(substitute);
      } catch (error) {
        substitute = { family: 'Inter', style: 'Regular' };
      }
      loaded = substitute;
      warn(
        want.family +
          ' ' +
          want.weight +
          ' is not available in this Figma account — substituted ' +
          loaded.family +
          ' ' +
          loaded.style +
          '. Install the font and run the plugin again for a file that matches the code.'
      );
    }
    FONTS[fontKey(want.family, want.weight)] = loaded;
  }
  log('Loaded ' + Object.keys(FONTS).length + ' font styles');
}

