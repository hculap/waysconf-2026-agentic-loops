async function buttonVariant(variant, state, size, page) {
  var look = BUTTON_LOOK[variant];
  var sizing = BUTTON_SIZES[size];
  var labelColour = look.label;
  var component = componentFrame('Variant=' + variant + ', State=' + state + ', Size=' + size, {
    dir: 'HORIZONTAL',
    gap: 8,
    justify: 'CENTER',
    align: 'CENTER',
    pad: { top: sizing.padY, bottom: sizing.padY, left: sizing.padX, right: sizing.padX },
    radius: 999
  });
  page.appendChild(component);
  bindNum(component, 'itemSpacing', 'space/2');
  bindNum(component, 'topLeftRadius', 'radius/pill');
  bindNum(component, 'topRightRadius', 'radius/pill');
  bindNum(component, 'bottomLeftRadius', 'radius/pill');
  bindNum(component, 'bottomRightRadius', 'radius/pill');

  if (state === 'disabled') {
    setFill(component, 'color/bg/raised');
    labelColour = 'color/text/secondary';
  } else if (look.fill) {
    setFill(component, look.fill);
  }
  if (state !== 'disabled' && look.stroke) {
    setStroke(component, look.stroke, 1, 'INSIDE');
    bindNum(component, 'strokeWeight', 'border/hairline');
  }

  var label = await text(sizing.style, labelColour, D.content.nav.cta.label, { name: 'button/label' });
  if (variant === 'ghost' && state === 'hover') label.textDecoration = 'UNDERLINE';
  append(component, label);

  var icon = chevron(sizing.icon, labelColour, 270);
  icon.name = 'button/icon';
  append(component, icon);
  icon.visible = false;

  try {
    component.minWidth = sizing.minWidth;
  } catch (error) {
    /* Older hosts hug; the padding still clears the touch target. */
  }
  setMinHeight(component, sizing.height);

  if (state === 'hover') hoverOverlay(component);
  if (state === 'focus') focusRing(component);

  component.description =
    'Label ' +
    labelColour.replace('color/', '') +
    ' on ' +
    (state === 'disabled' ? 'bg/raised' : look.fill ? look.fill.replace('color/', '') : 'transparent');
  return component;
}

