/* ==========================================================================
   8. Component properties
   --------------------------------------------------------------------------
   Variant properties come free from the variant names. Text properties have to
   be declared on the set and then referenced from the text node in every variant,
   which is what bindProp does.
   ========================================================================== */

function defineProp(set, setName, property, type, defaultValue) {
  var key = null;
  try {
    key = set.addComponentProperty(property, type, defaultValue);
  } catch (error) {
    warn('Could not add the ' + property + ' property to ' + setName + ': ' + error.message);
    return null;
  }
  if (!PROPS[setName]) PROPS[setName] = {};
  PROPS[setName][property] = key;
  return key;
}

/** Point every variant's named layer at the property, so an instance can drive it. */
function bindProp(set, setName, property, layerName, field) {
  var key = PROPS[setName] ? PROPS[setName][property] : null;
  if (!key) return;
  if (!LAYERS[setName]) LAYERS[setName] = {};
  LAYERS[setName][property] = layerName;
  var children = set.children;
  var i;
  for (i = 0; i < children.length; i = i + 1) {
    var node = find(children[i], layerName);
    if (!node) continue;
    try {
      var references = {};
      references[field || 'characters'] = key;
      node.componentPropertyReferences = references;
    } catch (error) {
      /* The instance override path below still works without the reference. */
    }
  }
}

/**
 * Set a value on an instance: through the component property when one is defined,
 * by overriding the named layer when one is not. Both are legitimate; the first
 * is what Dev Mode reports as a prop, so it is tried first.
 */
function setText(instance, setName, property, value) {
  var key = PROPS[setName] ? PROPS[setName][property] : null;
  if (key) {
    var payload = {};
    payload[key] = value;
    try {
      instance.setProperties(payload);
      return true;
    } catch (error) {
      /* Fall through to the layer override. */
    }
  }
  var layerName = LAYERS[setName] ? LAYERS[setName][property] : null;
  var node = layerName ? find(instance, layerName) : null;
  if (node && node.type === 'TEXT') {
    try {
      node.characters = value;
      return true;
    } catch (error) {
      warn('Could not set ' + property + ' on an instance of ' + setName);
    }
  }
  return false;
}

/** Override a named text layer directly, for content that is not a declared property. */
function overrideText(instance, layerName, value) {
  var node = find(instance, layerName);
  if (node && node.type === 'TEXT') {
    try {
      node.characters = value;
      return true;
    } catch (error) {
      /* A layer bound to a component property refuses a direct write. */
    }
  }
  return false;
}

function instance(setName, variantName) {
  var set = COMP[setName];
  if (!set) {
    warn('Component set ' + setName + ' is missing');
    return frame('missing/' + setName, {});
  }
  var source = set;
  if (set.type === 'COMPONENT_SET') {
    source = null;
    var children = set.children;
    var i;
    for (i = 0; i < children.length && !source; i = i + 1) {
      if (!variantName || children[i].name === variantName) source = children[i];
    }
    if (!source) source = set.defaultVariant || set.children[0];
  }
  return source.createInstance();
}

