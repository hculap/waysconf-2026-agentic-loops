async function clearPrevious() {
  step('Removing the previous TURBINE build');
  var i;

  var collections = [];
  if (typeof figma.variables.getLocalVariableCollectionsAsync === 'function') {
    collections = await figma.variables.getLocalVariableCollectionsAsync();
  } else if (typeof figma.variables.getLocalVariableCollections === 'function') {
    collections = figma.variables.getLocalVariableCollections();
  }
  for (i = 0; i < collections.length; i = i + 1) {
    if (collections[i].name.indexOf('TURBINE / ') === 0) {
      try {
        collections[i].remove();
      } catch (error) {
        warn('Could not remove the collection ' + collections[i].name);
      }
    }
  }

  var styles = [];
  if (typeof figma.getLocalTextStylesAsync === 'function') styles = await figma.getLocalTextStylesAsync();
  else if (typeof figma.getLocalTextStyles === 'function') styles = figma.getLocalTextStyles();
  var known = {};
  for (i = 0; i < D.textStyles.length; i = i + 1) known[D.textStyles[i].name] = true;
  for (i = 0; i < styles.length; i = i + 1) {
    if (known[styles[i].name]) {
      try {
        styles[i].remove();
      } catch (error) {
        /* A style still in use cannot be removed until its users are gone. */
      }
    }
  }

  var wanted = {};
  for (i = 0; i < D.pages.length; i = i + 1) wanted[D.pages[i]] = true;
  var pages = figma.root.children.slice();
  var survivor = null;
  for (i = 0; i < pages.length; i = i + 1) {
    if (!wanted[pages[i].name]) survivor = pages[i];
  }
  if (!survivor) {
    /* A document must always have at least one page, and every page this build
       made is about to be removed, so one has to be made first. The appendChild
       is not decoration: figma.createPage attaches the page in the editor, and
       relying on that rather than saying so is how the Cover page goes missing
       on the second run. */
    survivor = figma.createPage();
    survivor.name = 'Page 1';
    figma.root.appendChild(survivor);
  }
  await setCurrentPage(survivor);
  for (i = 0; i < pages.length; i = i + 1) {
    if (wanted[pages[i].name] && pages[i].id !== survivor.id) {
      try {
        pages[i].remove();
      } catch (error) {
        warn('Could not remove the page ' + pages[i].name);
      }
    }
  }
  log('Previous build removed');
}

function looksBuilt() {
  var pages = figma.root.children;
  var i;
  for (i = 0; i < pages.length; i = i + 1) {
    if (pages[i].name === 'Design system') return true;
  }
  return false;
}

