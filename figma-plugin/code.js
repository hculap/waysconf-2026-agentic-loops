/** FIGMA-SPEC §4: hover is a 10% text/primary overlay. It adds no fourteenth colour. */
function hoverOverlay(node) {
  var overlay = figma.createRectangle();
  overlay.name = 'overlay/hover';
  setFill(overlay, 'color/text/primary', 0.1);
  overlay.resize(Math.max(node.width, 1), Math.max(node.height, 1));
  overlay.cornerRadius = node.cornerRadius === figma.mixed ? 0 : node.cornerRadius;
  node.appendChild(overlay);
  absolute(overlay, { horizontal: 'STRETCH', vertical: 'STRETCH' });
  overlay.x = 0;
  overlay.y = 0;
  return overlay;
}

/**
 * FIGMA-SPEC §4: a 2px coolant stroke at 2px outside offset. Figma has no stroke
 * offset, so the ring is a real rectangle four pixels larger on every side. That is
 * also what the CSS will be — outline plus outline-offset — so the file and the code
 * describe the same object.
 */
function focusRing(node) {
  var ring = figma.createRectangle();
  ring.name = 'focus-ring';
  ring.fills = [];
  setStroke(ring, 'color/accent/coolant', 2, 'CENTER');
  ring.resize(Math.max(node.width + 8, 1), Math.max(node.height + 8, 1));
  ring.cornerRadius = node.cornerRadius === figma.mixed ? 4 : node.cornerRadius + 4;
  node.appendChild(ring);
  absolute(ring, { horizontal: 'STRETCH', vertical: 'STRETCH' });
  ring.x = -4;
  ring.y = -4;
  bindNum(ring, 'strokeWeight', 'border/focus');
  return ring;
}

