function createCollection(name, modeNames) {
  var collection = figma.variables.createVariableCollection(name);
  collection.renameMode(collection.modes[0].modeId, modeNames[0]);
  var i;
  for (i = 1; i < modeNames.length; i = i + 1) collection.addMode(modeNames[i]);
  COLLECTIONS[name] = collection;
  return collection;
}

function createVariable(name, collection, type) {
  try {
    return figma.variables.createVariable(name, collection, type);
  } catch (error) {
    /* Hosts before the object overload take the collection id. */
    return figma.variables.createVariable(name, collection.id, type);
  }
}

function modeIds(collection) {
  var ids = [];
  var i;
  for (i = 0; i < collection.modes.length; i = i + 1) ids.push(collection.modes[i].modeId);
  return ids;
}

function setDescription(variable, text) {
  if (!text) return;
  try {
    variable.description = text;
  } catch (error) {
    /* Descriptions are what Dev Mode hands back; losing one is not fatal. */
  }
}

async function buildVariables() {
  step('Creating variable collection TURBINE / Color');
  var colorCollection = createCollection('TURBINE / Color', ['Dark']);
  var darkMode = colorCollection.modes[0].modeId;
  var colours = D.tokens.color;
  var i;
  var j;

  /* Two passes: literals first, then the aliases that point at them. */
  for (i = 0; i < colours.length; i = i + 1) {
    if (colours[i].aliasOf) continue;
    var variable = createVariable(colours[i].name, colorCollection, 'COLOR');
    variable.setValueForMode(darkMode, {
      r: colours[i].rgb.r,
      g: colours[i].rgb.g,
      b: colours[i].rgb.b,
      a: 1
    });
    setDescription(variable, colours[i].description);
    V[colours[i].name] = variable;
    RGB[colours[i].name] = colours[i].rgb;
  }
  for (i = 0; i < colours.length; i = i + 1) {
    if (!colours[i].aliasOf) continue;
    var alias = createVariable(colours[i].name, colorCollection, 'COLOR');
    var target = V[colours[i].aliasOf];
    if (target) {
      alias.setValueForMode(darkMode, { type: 'VARIABLE_ALIAS', id: target.id });
    } else {
      alias.setValueForMode(darkMode, {
        r: colours[i].rgb.r,
        g: colours[i].rgb.g,
        b: colours[i].rgb.b,
        a: 1
      });
    }
    setDescription(alias, colours[i].description);
    V[colours[i].name] = alias;
    RGB[colours[i].name] = colours[i].rgb;
  }
  log(colours.length + ' colour variables, one mode, Dark');

  step('Creating variable collection TURBINE / Type');
  var typeCollection = createCollection('TURBINE / Type', ['Default']);
  var typeMode = typeCollection.modes[0].modeId;

  var families = D.tokens.type.family;
  for (i = 0; i < families.length; i = i + 1) {
    var familyVariable = createVariable(families[i].name, typeCollection, 'STRING');
    familyVariable.setValueForMode(typeMode, families[i].value);
    setDescription(familyVariable, 'CSS stack: ' + families[i].stack.join(', '));
    V[families[i].name] = familyVariable;
  }

  var numericGroups = [D.tokens.type.weight, D.tokens.type.size];
  for (i = 0; i < numericGroups.length; i = i + 1) {
    for (j = 0; j < numericGroups[i].length; j = j + 1) {
      var entry = numericGroups[i][j];
      var numeric = createVariable(entry.name, typeCollection, 'FLOAT');
      numeric.setValueForMode(typeMode, entry.value);
      if (entry.rem !== undefined) setDescription(numeric, entry.rem + 'rem');
      V[entry.name] = numeric;
    }
  }

  var leading = D.tokens.type.leading;
  for (i = 0; i < leading.length; i = i + 1) {
    var leadingVariable = createVariable(leading[i].name, typeCollection, 'FLOAT');
    leadingVariable.setValueForMode(typeMode, leading[i].percent);
    setDescription(leadingVariable, leading[i].percent + '% in Figma, ' + leading[i].css + ' unitless in CSS');
    V[leading[i].name] = leadingVariable;
  }

  var tracking = D.tokens.type.tracking;
  for (i = 0; i < tracking.length; i = i + 1) {
    var trackingVariable = createVariable(tracking[i].name, typeCollection, 'FLOAT');
    trackingVariable.setValueForMode(typeMode, tracking[i].percent);
    setDescription(trackingVariable, tracking[i].em + 'em — ' + tracking[i].source);
    V[tracking[i].name] = trackingVariable;
  }
  log('Type collection: families, weights, sizes, leading and tracking');

  step('Creating variable collection TURBINE / Scale');
  var scaleCollection = createCollection('TURBINE / Scale', ['Default']);
  var scaleMode = scaleCollection.modes[0].modeId;
  var scale = D.tokens.scale;
  for (i = 0; i < scale.length; i = i + 1) {
    var scaleVariable = createVariable(scale[i].name, scaleCollection, 'FLOAT');
    scaleVariable.setValueForMode(scaleMode, scale[i].value);
    setDescription(scaleVariable, scale[i].description);
    V[scale[i].name] = scaleVariable;
  }
  log(scale.length + ' scale variables');

  step('Creating variable collection TURBINE / Responsive');
  var responsiveCollection = createCollection('TURBINE / Responsive', D.tokens.responsive.modes);
  var responsiveModes = modeIds(responsiveCollection);
  var responsive = D.tokens.responsive.variables;
  for (i = 0; i < responsive.length; i = i + 1) {
    var record = responsive[i];
    var responsiveVariable = createVariable(record.name, responsiveCollection, 'FLOAT');
    for (j = 0; j < responsiveModes.length; j = j + 1) {
      /* The four type variables alias the fixed scale so a change propagates once. */
      var aliasName = record.alias ? record.alias[j] : null;
      var aliasTarget = aliasName ? V[aliasName] : null;
      if (aliasTarget) {
        responsiveVariable.setValueForMode(responsiveModes[j], {
          type: 'VARIABLE_ALIAS',
          id: aliasTarget.id
        });
      } else {
        responsiveVariable.setValueForMode(responsiveModes[j], record.values[j]);
      }
    }
    setDescription(responsiveVariable, record.note || '');
    V[record.name] = responsiveVariable;
  }
  log(responsive.length + ' responsive variables across three modes');
}

