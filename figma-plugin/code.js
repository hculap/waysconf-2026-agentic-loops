async function applyTextStyle(node, styleName) {
  var style = STYLES[styleName];
  if (!style) return;
  if (typeof node.setTextStyleIdAsync === 'function') {
    try {
      await node.setTextStyleIdAsync(style.id);
      return;
    } catch (error) {
      /* Fall through to the synchronous setter. */
    }
  }
  try {
    node.textStyleId = style.id;
  } catch (error) {
    warn('Could not apply text style ' + styleName);
  }
}

/**
 * Create a text node in a named style, filled from a colour variable.
 * The font for the style is already loaded; loadFonts() is the first thing that runs.
 */
async function text(styleName, colorVar, characters, options) {
  var o = options || {};
  var spec = SPEC[styleName] || { figmaFamily: 'Inter', weight: 400 };
  var node = figma.createText();
  node.fontName = fontFor(spec.figmaFamily, spec.weight);
  node.characters = characters === undefined || characters === null ? '' : String(characters);
  await applyTextStyle(node, styleName);
  setFill(node, colorVar);
  node.name = o.name || styleName.split('/')[1].toLowerCase();
  if (o.align) node.textAlignHorizontal = o.align;
  if (o.size) node.fontSize = o.size;
  if (o.decoration) node.textDecoration = o.decoration;
  return node;
}

/** The common case: make a text node and put it somewhere. */
async function addText(parent, styleName, colorVar, characters, options) {
  var o = options || {};
  var node = await text(styleName, colorVar, characters, o);
  append(parent, node, o.h, o.v);
  if (o.maxWidth) setMaxWidth(node, o.maxWidth);
  return node;
}

