#!/usr/bin/env node
/**
 * Put the eight prompts inside the deck.
 *
 *   node scripts/build-deck-prompts.mjs
 *
 * The deck shows an opening of each prompt, not the whole thing: prompt 02 alone is sixty
 * lines, which is a wall on a projector and useless to read out. What the slide carries is
 * the first few lines, a Copy button holding the FULL text, and a link to that prompt's
 * section on the workshop page.
 *
 * The text is taken from prompts/NN-*.md at build time and bundled into the deck, so:
 *   - the slide cannot drift from the prompt the room is pasting
 *   - the Copy button works with no network, which is the only state a conference guarantees
 *
 * Writes deck/prompts.generated.ts. Never edit that file; edit prompts/ and run this.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'prompts')
const OUT = join(ROOT, 'deck/prompts.generated.ts')
const PAGE = 'https://waysconf.szymonpaluch.com/workshop/'

// How much of a prompt a slide shows. Measured against the deck's canvas, not guessed: more
// than this and the card runs past the bottom edge, which the deck gate fails.
const PREVIEW_LINES = 9

/** Every ```text block in a prompt file, in order. The first is the one that gets pasted. */
function textBlocks(md) {
  const out = []
  const lines = md.split('\n')
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trim() !== '```text') continue
    const body = []
    for (i++; i < lines.length && !lines[i].startsWith('```'); i++) body.push(lines[i])
    out.push(body.join('\n').trim())
  }
  return out
}

const files = (await readdir(SRC)).filter((f) => /^0\d-.*\.md$/.test(f)).sort()
if (files.length !== 8) throw new Error(`expected eight prompts in prompts/, found ${files.length}`)

const prompts = []
for (const file of files) {
  const md = await readFile(join(SRC, file), 'utf8')
  const n = file.slice(0, 2)
  const heading = md.match(/^#\s+\d+\s+—\s+(.+)$/m)
  if (!heading) throw new Error(`${file}: no "# NN — Title" heading to take the title from`)

  const blocks = textBlocks(md)
  if (!blocks.length) throw new Error(`${file}: no \`\`\`text block, so there is nothing to copy`)
  const text = blocks[0]

  // The opening of the prompt, whole lines only — a preview cut mid-sentence reads as a bug.
  const all = text.split('\n')
  const preview = all.slice(0, PREVIEW_LINES).join('\n').trimEnd()

  prompts.push({
    n,
    title: heading[1],
    href: `${PAGE}#p${n}`,
    preview,
    text,
    lines: all.length,
    words: text.split(/\s+/).filter(Boolean).length,
    parts: blocks.length,
  })
}

const body = `// Generated by scripts/build-deck-prompts.mjs from prompts/. Do not edit.
//
// The full text of each prompt travels inside the deck so the Copy button works offline and
// cannot disagree with what the workshop page serves. Regenerate after any change to prompts/.

export interface DeckPrompt {
  /** "01" … "08" */
  n: string
  title: string
  /** that prompt's section on the workshop page */
  href: string
  /** the opening lines, for the slide */
  preview: string
  /** the whole first block — what the Copy button puts on the clipboard */
  text: string
  lines: number
  words: number
  /** how many pasteable blocks the prompt has; more than one means a follow-up on the page */
  parts: number
}

export const prompts: DeckPrompt[] = ${JSON.stringify(prompts, null, 2)}

export const promptByNumber = (n: string): DeckPrompt => {
  const found = prompts.find((p) => p.n === n)
  if (!found) throw new Error(\`no prompt \${n}: the deck asked for a prompt that prompts/ does not have\`)
  return found
}
`

await writeFile(OUT, body)
console.log(`wrote deck/prompts.generated.ts  ${prompts.length} prompts`)
for (const p of prompts) {
  console.log(`  ${p.n}  ${String(p.lines).padStart(3)} lines, ${String(p.words).padStart(4)} words${p.parts > 1 ? `, ${p.parts} parts` : ''}  →  ${p.title}`)
}
